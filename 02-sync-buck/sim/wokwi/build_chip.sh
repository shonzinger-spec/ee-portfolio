#!/usr/bin/env bash
# Builds buck_plant.chip.wasm with the WASI-SDK clang that wokwi-cli installs
# (~/.wokwi/wasi-sdk; override with WASI_SDK=...). Same flags as wokwi/inverter-chip.
# plant.c is #included from test/host, buck_config.h comes from src/buck_ctrl.
#   ./build_chip.sh        -> buck_plant.chip.wasm
#   ./build_chip.sh --web  -> also web/buck_plant.chip.c: one self-contained file (buck_config.h,
#                             plant.h and plant.c inlined) for the wokwi.com custom-chip editor,
#                             compiled here once as a check
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
sdk="${WASI_SDK:-$HOME/.wokwi/wasi-sdk}"
cd "$here"
if [ ! -f wokwi-api.h ]; then   # not in git (repo .gitignore); the header wokwi-cli's 'chip compile' fetches
  echo "wokwi-api.h missing: save https://wokwi.com/api/chips/wokwi-api.h as sim/wokwi/wokwi-api.h" >&2
  exit 1
fi
cc=("$sdk/bin/clang" --target=wasm32-unknown-wasi --sysroot "$sdk/share/wasi-sysroot"
    -nostartfiles -Wl,--import-memory -Wl,--export-table -Wl,--no-entry -O2 -Wall -Wextra -Werror)
"${cc[@]}" -I . -I ../../test/host -I ../../src/buck_ctrl -o buck_plant.chip.wasm buck_plant.chip.c
ls -l buck_plant.chip.wasm
if [ "${1:-}" = "--web" ]; then
  mkdir -p web
  {
    echo "// Generated by build_chip.sh --web: buck_config.h + plant.h + plant.c + buck_plant.chip.c"
    sed -e '/^#include "/d' ../../src/buck_ctrl/buck_config.h
    sed -e '/^#include "/d' ../../test/host/plant.h
    sed -e '/^#include "/d' ../../test/host/plant.c
    sed -e '/^#include "plant.c"/d' buck_plant.chip.c
  } > web/buck_plant.chip.c
  cp buck_plant.chip.json diagram.json web/
  "${cc[@]}" -I . -o web/check.wasm web/buck_plant.chip.c && rm web/check.wasm
  echo "web/buck_plant.chip.c compiles"
fi
