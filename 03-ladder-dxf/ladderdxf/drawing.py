"""Lay a Ladder out on an ANSI B sheet (17 x 11 in, landscape) and write it as DXF R2010."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import ezdxf
from ezdxf.enums import TextEntityAlignment as Align

from . import __version__, symbols
from .model import COILS, CONTACTS, FIRST_LINE, RAILS, Element, InputError, Ladder, Rung
from .symbols import CELL_W, TB_H, TB_W

SHEET_W, SHEET_H, MARGIN = 17.0, 11.0, 0.5
RAIL_X = (2.0, 12.0)  # L1, L2
TOP_Y, SPACING = 9.5, 0.75  # y of the first line, distance between line references
PITCH = 1.25  # distance between symbol slots on a line
FIRST_SLOT_X = RAIL_X[0] + 0.5  # inputs fill slots from the left rail ...
LAST_SLOT_X = RAIL_X[1] - 0.5 - CELL_W  # ... the load and its overload contacts from the right rail
BRANCH_GAP = 0.25  # branch verticals sit this far outside the symbol they bridge
LINES_PER_SHEET = int((TOP_Y - (MARGIN + TB_H + 0.5)) / SPACING + 1e-9) + 1
SLOTS_PER_LINE = int((LAST_SLOT_X - FIRST_SLOT_X) / PITCH + 1e-9) + 1
LAYERS = ("BORDER", "TITLE", "NOTES", "LADDER", "LINENO", "WIRES", "WIRENO", "SYMS", "TAGS", "DESC", "XREF", "TERMS", "MFGCAT")
NOTES = (
    "NOTES:",
    "1. NEMA/JIC SYMBOLS. UNITS: INCHES. SHEET: ANSI B.",
    "2. LINE REFERENCES LEFT OF L1. COIL CROSS-REFERENCES RIGHT OF L2 (LINES OF ITS NO / NC CONTACTS).",
    "3. NUMBER UNDER A CONTACT = LINE OF ITS COIL. SMALL NUMBERS AT SYMBOL ENDS = TERMINALS.",
    "4. WIRE 1 = L1, WIRE 2 = L2 (120 VAC CONTROL POWER).",
)


@dataclass
class TitleInfo:
    project: str = "EE PORTFOLIO"
    title: str = "MOTOR STARTER"
    subtitle: str = "CONTROL SCHEMATIC"
    dwg_no: str = "LDX-001"
    sheet: str = "1 OF 1"
    rev: str = "A"
    date: str = ""
    drawn: str = ""
    scale: str = "NTS"

    def attribs(self) -> dict[str, str]:
        return {
            "PROJECT": self.project, "TITLE1": self.title, "TITLE2": self.subtitle, "DWGNO": self.dwg_no,
            "SHEET": self.sheet, "REV": self.rev, "DATE": self.date, "DRAWN": self.drawn, "SCALE": self.scale,
        }


def line_y(line: int) -> float:
    return TOP_Y - (line - FIRST_LINE) * SPACING


def slot_xs(rung: Rung) -> list[float]:
    """Left edge of each main-path symbol: inputs from the left rail, load and overloads from the right."""
    n, k = len(rung.main), rung.load_index
    xs = [FIRST_SLOT_X + i * PITCH if i < k else LAST_SLOT_X - (n - 1 - i) * PITCH for i in range(n)]
    if xs[0] < FIRST_SLOT_X - 1e-9 or (k and xs[k] - xs[k - 1] < PITCH - 1e-9):
        raise InputError(f"rung {rung.number}: {n} symbols do not fit on one line (a line holds {SLOTS_PER_LINE})")
    return xs


def build_document(ladder: Ladder, title: TitleInfo):
    used = ladder.last_line - FIRST_LINE + 1
    if used > LINES_PER_SHEET:
        raise InputError(f"the ladder needs {used} lines but a sheet holds {LINES_PER_SHEET}; v0 draws a single sheet")
    slots = [slot_xs(r) for r in ladder.rungs]  # check every rung fits before drawing anything
    doc = ezdxf.new("R2010", setup=False)
    doc.header["$INSUNITS"] = 1  # inches
    doc.header["$MEASUREMENT"] = 0  # imperial
    for name in LAYERS:
        doc.layers.add(name, color=7)
    symbols.define_blocks(doc)
    msp = doc.modelspace()
    _sheet(msp, title)
    _rails(msp)
    for rung, xs in zip(ladder.rungs, slots):
        _rung(msp, ladder, rung, xs)
    doc.set_modelspace_vport(height=SHEET_H + 0.5, center=(SHEET_W / 2, SHEET_H / 2))
    return doc


def write_dxf(ladder: Ladder, path, title: TitleInfo) -> Path:
    build_document(ladder, title).saveas(path)
    return Path(path)


def _sheet(msp, title: TitleInfo) -> None:
    w, h, m = SHEET_W, SHEET_H, MARGIN
    msp.add_lwpolyline([(m, m), (w - m, m), (w - m, h - m), (m, h - m)], close=True, dxfattribs={"layer": "BORDER"})
    block = msp.add_blockref("TITLE_BLOCK", (w - m - TB_W, m), dxfattribs={"layer": "TITLE"})
    symbols.attach_attribs(block, title.attribs())
    for i, note in enumerate(NOTES):
        _text(msp, note, (m + 0.25, m + TB_H - 0.2 - i * 0.22), 0.09, "NOTES", Align.MIDDLE_LEFT)
    _text(msp, f"GENERATED BY LADDERDXF {__version__}", (m + 0.25, m + 0.2), 0.07, "NOTES", Align.MIDDLE_LEFT)


def _rails(msp) -> None:
    top, bottom = TOP_Y + 0.3, line_y(FIRST_LINE + LINES_PER_SHEET - 1) - 0.3
    for (name, wire), x, side in zip(RAILS, RAIL_X, (1, -1)):
        msp.add_line((x, top), (x, bottom), dxfattribs={"layer": "LADDER"})
        _text(msp, name, (x, top + 0.2), 0.125, "LADDER")
        _wireno(msp, wire, (x + side * 0.15, top - 0.12))
    _text(msp, "120 VAC CONTROL", (sum(RAIL_X) / 2, top + 0.2), 0.125, "LADDER")
    for i in range(LINES_PER_SHEET):
        _text(msp, str(FIRST_LINE + i), (RAIL_X[0] - 0.3, line_y(FIRST_LINE + i)), 0.125, "LINENO", Align.MIDDLE_RIGHT)


def _rung(msp, ladder: Ladder, rung: Rung, xs: list[float]) -> None:
    y = line_y(rung.line)
    ends = [RAIL_X[0], *(v for x in xs for v in (x, x + CELL_W)), RAIL_X[1]]
    for k in range(len(xs) + 1):  # wire k runs into node k; nodes 0 and len(xs) are the rails
        x1, x2 = ends[2 * k], ends[2 * k + 1]
        _wire(msp, (x1, y), (x2, y))
        if 0 < k < len(xs):
            _wireno(msp, rung.nodes[k], (x1 + min((x2 - x1) / 2, 0.375), y + 0.09))
    for el, x in zip(rung.main, xs):
        _symbol(msp, ladder, el, x, y)

    lowest = {target: b for b, target in zip(rung.branches, rung.targets)}  # last branch under each target
    reached: dict[int, float] = {}  # target -> y the branch verticals have reached so far
    for b, target in zip(rung.branches, rung.targets):
        x, yb = xs[target], line_y(b.line)
        xl, xr = x - BRANCH_GAP, x + CELL_W + BRANCH_GAP
        if target not in reached:
            _dot(msp, (xl, y))
            _dot(msp, (xr, y))
        y0, reached[target] = reached.get(target, y), yb
        for xv in (xl, xr):
            _wire(msp, (xv, y0), (xv, yb))
        _wire(msp, (xl, yb), (x, yb))
        _wire(msp, (x + CELL_W, yb), (xr, yb))
        if lowest[target] is not b:
            _dot(msp, (xl, yb))
            _dot(msp, (xr, yb))
        _symbol(msp, ladder, b, x, yb)


def _symbol(msp, ladder: Ladder, el: Element, x: float, y: float) -> None:
    ref = msp.add_blockref(el.spec.block, (x, y), dxfattribs={"layer": "SYMS"})
    values = {"TERM01": el.pins[0], "TERM02": el.pins[1]}
    moves = None
    if el.kind in CONTACTS:
        values.update(TAG2=el.tag, XREF=el.xref)
    else:
        values.update(TAG1=el.tag, DESC1=el.description, MFG=el.manufacturer, CAT=el.catalog, COLOR=el.color_letter)
        if el.kind in COILS:
            dev = ladder.device(el.device)
            no = "NO " + ",".join(map(str, dev.xref_no)) if dev.xref_no else ""
            nc = "NC " + ",".join(map(str, dev.xref_nc)) if dev.xref_nc else ""
            dy = 0.08 if no and nc else 0.0
            values.update(XREFNO=no, XREFNC=nc)
            right = RAIL_X[1] + 0.15
            moves = {"XREFNO": ((right, y + dy), Align.MIDDLE_LEFT), "XREFNC": ((right, y - dy), Align.MIDDLE_LEFT)}
    symbols.attach_attribs(ref, values, moves)


def _text(msp, text: str, point, height: float, layer: str, align: Align = Align.MIDDLE_CENTER) -> None:
    msp.add_text(text, height=height, dxfattribs={"layer": layer}).set_placement(point, align=align)


def _wire(msp, p1, p2) -> None:
    msp.add_line(p1, p2, dxfattribs={"layer": "WIRES"})


def _dot(msp, point) -> None:
    msp.add_blockref("DOT", point, dxfattribs={"layer": "WIRES"})


def _wireno(msp, number: str, point) -> None:
    symbols.attach_attribs(msp.add_blockref("WIRENO", point, dxfattribs={"layer": "WIRENO"}), {"WIRENO": number})
